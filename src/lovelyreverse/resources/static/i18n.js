let LV_LANG = (typeof localStorage !== "undefined" && localStorage.getItem("lv.lang")) || "zh";

function t(key, params) {
  const dict = LV_I18N[LV_LANG] || LV_I18N.zh;
  let s = (key in dict) ? dict[key] : (LV_I18N.en[key] ?? key);
  if (params) {
    for (const k of Object.keys(params)) s = s.split("{" + k + "}").join(String(params[k]));
  }
  return s;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  scope.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = LV_LANG === "zh" ? "zh-CN" : "en";
  document.title = t("doc.title");
}

function setLang(lang) {
  LV_LANG = (lang === "en") ? "en" : "zh";
  try { localStorage.setItem("lv.lang", LV_LANG); } catch (e) { /* private mode */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent("lv:langchange"));
}
